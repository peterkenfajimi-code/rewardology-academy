/**
 * Create (or reuse) the Africa Benefits Repository Supabase project,
 * write repository env vars to .env.local, apply schema, and sync Netlify.
 *
 * Requires SUPABASE_ACCESS_TOKEN in .env.local (same org token as Academy scripts).
 * Optional: NETLIFY_AUTH_TOKEN for deploy env sync.
 *
 * Usage: node scripts/setup-benefits-repository.mjs
 */
import crypto from "crypto";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import {
  getProjectRoot,
  loadEnvLocal,
  resolveProjectRoot,
} from "./lib/load-env-local.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = resolveProjectRoot(getProjectRoot(import.meta.url));
const env = loadEnvLocal(root);
const token =
  process.env.REPOSITORY_SUPABASE_ACCESS_TOKEN ||
  process.env.SUPABASE_ACCESS_TOKEN ||
  env.REPOSITORY_SUPABASE_ACCESS_TOKEN ||
  env.SUPABASE_ACCESS_TOKEN;

const PROJECT_NAME = "rewardology-benefits-repository";
const API = "https://api.supabase.com/v1";

if (!token) {
  console.error(`
Missing SUPABASE_ACCESS_TOKEN in .env.local.

Generate one at https://supabase.com/dashboard/account/tokens
Then re-run: node scripts/setup-benefits-repository.mjs
`);
  process.exit(1);
}

const headers = {
  Authorization: `Bearer ${token}`,
  "Content-Type": "application/json",
};

async function api(pathname, options = {}) {
  const res = await fetch(`${API}${pathname}`, { ...options, headers });
  const text = await res.text();
  let data;
  try {
    data = text ? JSON.parse(text) : null;
  } catch {
    data = text;
  }
  if (!res.ok) {
    throw new Error(`${options.method ?? "GET"} ${pathname} → ${res.status}: ${text.slice(0, 400)}`);
  }
  return data;
}

function randomSecret(bytes = 32) {
  return crypto.randomBytes(bytes).toString("hex");
}

function upsertEnvLocal(vars) {
  const envPath = path.join(root, ".env.local");
  const keys = new Set(Object.keys(vars));
  const lines = fs.existsSync(envPath) ? fs.readFileSync(envPath, "utf8").split(/\r?\n/) : [];
  const kept = lines.filter((line) => {
    const t = line.trim();
    if (!t || t.startsWith("#")) return true;
    const i = t.indexOf("=");
    if (i === -1) return true;
    return !keys.has(t.slice(0, i).trim());
  });
  while (kept.length && kept[kept.length - 1] === "") kept.pop();
  kept.push("", "# Africa Benefits Repository (auto-generated by setup-benefits-repository.mjs)");
  for (const [key, value] of Object.entries(vars)) {
    kept.push(`${key}=${value}`);
  }
  kept.push("");
  fs.writeFileSync(envPath, kept.join("\n"), "utf8");
}

async function waitForProject(ref, attempts = 40) {
  for (let i = 0; i < attempts; i += 1) {
    const project = await api(`/projects/${ref}`);
    const status = project.status ?? project.project?.status;
    console.log(`Project status: ${status ?? "unknown"} (${i + 1}/${attempts})`);
    if (status === "ACTIVE_HEALTHY" || status === "ACTIVE") return project;
    await new Promise((r) => setTimeout(r, 15000));
  }
  throw new Error(`Project ${ref} did not become active in time`);
}

async function findOrCreateProject() {
  const existingRef =
    process.env.REPOSITORY_SUPABASE_PROJECT_REF || env.REPOSITORY_SUPABASE_PROJECT_REF;
  if (existingRef) {
    console.log(`Using existing project ref from env: ${existingRef}`);
    const project = await api(`/projects/${existingRef}`);
    return { ref: existingRef, project, created: false };
  }

  const projects = await api("/projects");
  const match = projects.find(
    (p) =>
      p.name === PROJECT_NAME ||
      p.name?.toLowerCase().includes("benefits-repository") ||
      p.name?.toLowerCase().includes("benefits repository")
  );
  if (match) {
    console.log(`Found existing project: ${match.name} (${match.id})`);
    return { ref: match.id, project: match, created: false };
  }

  const orgs = await api("/organizations");
  if (!orgs?.length) throw new Error("No Supabase organizations found for this token");
  const org = orgs[0];
  console.log(`Creating project in org: ${org.name} (${org.id})`);

  const dbPass = randomSecret(18);
  const body = {
    name: PROJECT_NAME,
    organization_id: org.id,
    db_pass: dbPass,
    region: "eu-west-1",
    plan: "free",
  };

  const created = await api("/projects", { method: "POST", body: JSON.stringify(body) });
  const ref = created.id ?? created.ref;
  console.log(`Created project ${PROJECT_NAME} → ${ref}`);
  console.log("(Database password was generated — stored only in Supabase, not written to .env.local)");
  return { ref, project: created, created: true };
}

async function fetchApiKeys(ref) {
  const keys = await api(`/projects/${ref}/api-keys?reveal=true`);
  const anon = keys.find((k) => k.name === "anon" || k.type === "anon");
  const service = keys.find((k) => k.name === "service_role" || k.type === "service_role");
  if (!anon?.api_key || !service?.api_key) {
    throw new Error("Could not retrieve anon/service_role API keys");
  }
  return { anonKey: anon.api_key, serviceKey: service.api_key };
}

async function applySchema(ref) {
  const sqlPath = path.join(root, "supabase", "benefits-repository", "schema.sql");
  const query = fs.readFileSync(sqlPath, "utf8");
  const res = await fetch(`${API}/projects/${ref}/database/query`, {
    method: "POST",
    headers,
    body: JSON.stringify({ query }),
  });
  const body = await res.text();
  if (!res.ok) throw new Error(`Schema apply failed: ${res.status} ${body.slice(0, 400)}`);

  const verify = await fetch(`${API}/projects/${ref}/database/query`, {
    method: "POST",
    headers,
    body: JSON.stringify({ query: "select count(*)::int as country_modules from country_modules;" }),
  });
  const verifyBody = await verify.text();
  if (!verify.ok) throw new Error(`Schema verify failed: ${verifyBody.slice(0, 400)}`);
  console.log("Schema applied. Verification:", verifyBody);
}

async function syncNetlify(repositoryVars) {
  const netlifyToken = process.env.NETLIFY_AUTH_TOKEN || env.NETLIFY_AUTH_TOKEN;
  if (!netlifyToken) {
    console.log("Skipping Netlify sync (NETLIFY_AUTH_TOKEN not set).");
    return;
  }

  const NETLIFY_SITE_SLUG = "effulgent-cajeta-57593b";
  const listRes = await fetch("https://api.netlify.com/api/v1/sites", {
    headers: { Authorization: `Bearer ${netlifyToken}` },
  });
  if (!listRes.ok) throw new Error(`Netlify list sites failed: ${listRes.status}`);
  const sites = await listRes.json();
  const site = sites.find((s) => s.subdomain === NETLIFY_SITE_SLUG);
  if (!site) throw new Error(`Netlify site ${NETLIFY_SITE_SLUG} not found`);

  const existingRes = await fetch(`https://api.netlify.com/api/v1/sites/${site.id}/env`, {
    headers: { Authorization: `Bearer ${netlifyToken}` },
  });
  const existingVars = existingRes.ok ? await existingRes.json() : [];
  const existingKeys = new Set(existingVars.map((v) => v.key));
  const accountId = site.account_id || site.account_slug;

  for (const [key, value] of Object.entries(repositoryVars)) {
    const body = { key, values: [{ context: "all", value }] };
    const siteQuery = `site_id=${site.id}`;
    const url = existingKeys.has(key)
      ? `https://api.netlify.com/api/v1/accounts/${accountId}/env/${encodeURIComponent(key)}?${siteQuery}`
      : `https://api.netlify.com/api/v1/accounts/${accountId}/env?${siteQuery}`;
    const method = existingKeys.has(key) ? "PUT" : "POST";
    const payload = existingKeys.has(key) ? body : [body];
    const res = await fetch(url, {
      method,
      headers: { Authorization: `Bearer ${netlifyToken}`, "Content-Type": "application/json" },
      body: JSON.stringify(payload),
    });
    if (!res.ok) throw new Error(`Netlify set ${key} failed: ${await res.text()}`);
    console.log(existingKeys.has(key) ? "Netlify updated" : "Netlify created", key);
  }
}

async function main() {
  const { ref, created } = await findOrCreateProject();
  if (created) await waitForProject(ref);

  const { anonKey, serviceKey } = await fetchApiKeys(ref);
  const projectUrl = `https://${ref}.supabase.co`;

  const adminUser = env.REPOSITORY_ADMIN_USERNAME || "repository-admin";
  const adminPass = env.REPOSITORY_ADMIN_PASSWORD || randomSecret(12);
  const sessionToken = env.REPOSITORY_ADMIN_SESSION_TOKEN || randomSecret(24);

  const repositoryVars = {
    NEXT_PUBLIC_REPOSITORY_SUPABASE_URL: projectUrl,
    NEXT_PUBLIC_REPOSITORY_SUPABASE_ANON_KEY: anonKey,
    REPOSITORY_SUPABASE_SERVICE_KEY: serviceKey,
    REPOSITORY_SUPABASE_PROJECT_REF: ref,
    REPOSITORY_SUPABASE_ACCESS_TOKEN: token,
    REPOSITORY_ADMIN_USERNAME: adminUser,
    REPOSITORY_ADMIN_PASSWORD: adminPass,
    REPOSITORY_ADMIN_SESSION_TOKEN: sessionToken,
  };

  const netlifyVars = { ...repositoryVars };
  if (env.ANTHROPIC_API_KEY?.trim()) {
    netlifyVars.ANTHROPIC_API_KEY = env.ANTHROPIC_API_KEY.trim();
  }

  upsertEnvLocal(repositoryVars);
  console.log("\nUpdated .env.local with repository credentials.");
  console.log(`Admin username: ${adminUser}`);
  console.log("Admin password: see REPOSITORY_ADMIN_PASSWORD in .env.local");

  if (!env.ANTHROPIC_API_KEY?.trim()) {
    console.warn(
      "\nANTHROPIC_API_KEY is not set — add it to .env.local for AI extraction in /repository-admin."
    );
    console.warn("Get a key at https://console.anthropic.com/settings/keys");
  }

  await applySchema(ref);
  try {
    await syncNetlify({ ...repositoryVars, ...netlifyVars });
  } catch (err) {
    console.warn("\nNetlify sync skipped or failed:", err instanceof Error ? err.message : err);
    console.warn("Add NETLIFY_AUTH_TOKEN to .env.local and re-run setup, or set vars manually in Netlify.");
  }

  console.log("\nDone.");
  console.log(`Supabase project: ${projectUrl}`);
  console.log("Admin tool (local): http://localhost:3000/repository-admin/login");
  console.log("Public preview: /benefits-repository");
}

main().catch((err) => {
  console.error(err.message || err);
  process.exit(1);
});
